/* tools/w32nlsdump.c -- W7s: dump Windows 11's NLS answers as a C header
 * for tobyOS (src/win32_nls_data.h): code pages, their best-fit reverse maps, Unicode case
 * mapping and character classes, the CRT's ctype tables per code page, and
 * named locales' data. Every value is what this machine's Windows answers.
 * Built and run on Windows (the UCRT gcc):
 *   gcc -O1 -o w32nlsdump.exe tools/w32nlsdump.c && w32nlsdump > src/win32_nls_data.h */
#include <windows.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <locale.h>
#include <ctype.h>
#include <wctype.h>

static const UINT g_cps[] = { 1252, 1250, 1251, 1254, 437, 850, 852, 857, 866, 28591, 20127 };
#define NCP (sizeof g_cps / sizeof g_cps[0])
static const wchar_t *g_locs[] = { L"en-US", L"en-GB", L"de-DE", L"fr-FR", L"es-ES", L"ru-RU", L"sv-SE", L"tr-TR", L"pl-PL", L"" };
static const char *g_locsa[] = { "en-US", "en-GB", "de-DE", "fr-FR", "es-ES", "ru-RU", "sv-SE", "tr-TR", "pl-PL", "" };
#define NLOC (sizeof g_locs / sizeof g_locs[0])

static void emit_u16str(const wchar_t *s, int n) {
    printf("u\"");
    for (int i = 0; i < n; i++) {
        unsigned c = s[i];
        if (c == '"' || c == '\\') printf("\\%c", (char)c);
        else if (c >= 0x20 && c < 0x7F) printf("%c", (char)c);
        else printf("\\u%04X", c);
    }
    printf("\"");
}

int main(void) {
    printf("/* src/win32_nls_data.h -- generated by tools/w32nlsdump.c on Windows 11: the\n"
           " * answers of this machine's Windows (ACP %u, OEMCP %u), not hand-written. */\n", GetACP(), GetOEMCP());
    printf("#define W32NLS_ACP %u\n#define W32NLS_OEMCP %u\n", GetACP(), GetOEMCP());

    /* code pages: bytes 0x80..0xFF -> UTF-16 (0xFFFF: no character; MB_ERR_INVALID_CHARS says so) */
    printf("#define W32NLS_NCP %d\nstatic const uint16_t w32nls_cp_id[W32NLS_NCP] = {", (int)NCP);
    for (unsigned i = 0; i < NCP; i++) printf("%s%u", i ? ", " : " ", g_cps[i]);
    printf(" };\nstatic const uint16_t w32nls_cp_hi[W32NLS_NCP][128] = {\n");
    for (unsigned i = 0; i < NCP; i++) {
        printf("    {");
        for (int b = 0x80; b < 0x100; b++) {
            char c = (char)b; wchar_t w = 0;
            int n = MultiByteToWideChar(g_cps[i], MB_ERR_INVALID_CHARS, &c, 1, &w, 1);
            int n2 = MultiByteToWideChar(g_cps[i], 0, &c, 1, &w, 1);
            (void)n2;
            printf("%s0x%04X", (b & 15) ? "," : (b == 0x80 ? "" : ",\n     "), n == 1 ? (unsigned)w : 0xFFFFu);
        }
        printf(" },\n");
    }
    printf("};\n");
    /* what MB_ERR_INVALID_CHARS refuses, as the plain call reads it: 1 bit per byte */
    printf("static const uint16_t w32nls_cp_plain[W32NLS_NCP][128] = {\n");
    for (unsigned i = 0; i < NCP; i++) {
        printf("    {");
        for (int b = 0x80; b < 0x100; b++) {
            char c = (char)b; wchar_t w = 0;
            MultiByteToWideChar(g_cps[i], 0, &c, 1, &w, 1);
            printf("%s0x%04X", (b & 15) ? "," : (b == 0x80 ? "" : ",\n     "), w);
        }
        printf(" },\n");
    }
    printf("};\n");

    /* reverse: every UTF-16 unit 0x80..0xFFFF (no surrogates) that WideCharToMultiByte
     * writes as a byte other than the default -- exact or best fit */
    for (unsigned i = 0; i < NCP; i++) {
        printf("static const uint8_t w32nls_rev_%u[][3] = {   /* {lo, hi, byte}: U+hilo is written as byte -- its own or the best fit */\n", g_cps[i]);
        int cnt = 0;
        printf("    ");
        for (unsigned u = 0x80; u < 0x10000; u++) {
            if (u >= 0xD800 && u < 0xE000) continue;
            wchar_t w = (wchar_t)u; char b = 0; BOOL used = FALSE;
            int n = WideCharToMultiByte(g_cps[i], 0, &w, 1, &b, 1, NULL, &used);
            if (n != 1 || used) continue;
            printf("{0x%02X,0x%02X,0x%02X},", u & 0xFF, u >> 8, (unsigned char)b);
            if (++cnt % 8 == 0) printf("\n    ");
        }
        printf("{0,0,0} };\n");
        /* exact ones: those NO_BEST_FIT keeps */
        printf("static const uint8_t w32nls_exact_%u[][2] = {   /* U+hilo written exactly (WC_NO_BEST_FIT_CHARS keeps it) */\n    ", g_cps[i]);
        cnt = 0;
        for (unsigned u = 0x80; u < 0x10000; u++) {
            if (u >= 0xD800 && u < 0xE000) continue;
            wchar_t w = (wchar_t)u; char b = 0; BOOL used = FALSE;
            int n = WideCharToMultiByte(g_cps[i], WC_NO_BEST_FIT_CHARS, &w, 1, &b, 1, NULL, &used);
            if (n != 1 || used) continue;
            printf("{0x%02X,0x%02X},", u & 0xFF, u >> 8);
            if (++cnt % 10 == 0) printf("\n    ");
        }
        printf("{0,0} };\n");
    }

    /* Unicode case mapping (LCMapStringEx, the invariant locale) as runs:
     * {first, last, delta, step} */
    for (int up = 1; up >= 0; up--) {
        printf("static const int32_t w32nls_%s[][4] = {\n    ", up ? "upper" : "lower");
        int cnt = 0;
        unsigned rs = 0, rl = 0; int rd = 0, rstep = 0; int open = 0;
        for (unsigned u = 0; u < 0x10000; u++) {
            if (u >= 0xD800 && u < 0xE000) continue;
            wchar_t w = (wchar_t)u, o = 0;
            LCMapStringEx(L"", up ? LCMAP_UPPERCASE : LCMAP_LOWERCASE, &w, 1, &o, 1, 0, 0, 0);
            int d = (int)o - (int)u;
            if (!d) continue;
            if (open && d == rd && (u - rl == (unsigned)rstep || (rstep == 0 && (u - rl == 1 || u - rl == 2)))) {
                if (!rstep) rstep = (int)(u - rl);
                rl = u;
                continue;
            }
            if (open) { printf("{0x%04X,0x%04X,%d,%d},", rs, rl, rd, rstep ? rstep : 1); if (++cnt % 4 == 0) printf("\n    "); }
            open = 1; rs = rl = u; rd = d; rstep = 0;
        }
        if (open) printf("{0x%04X,0x%04X,%d,%d},", rs, rl, rd, rstep ? rstep : 1);
        printf("{-1,-1,0,0} };\n");
    }
    /* the CRT's towupper/towlower: the cases where they differ from LCMapStringEx's */
    {
        int du = 0, dl = 0;
        for (unsigned u = 0; u < 0x10000; u++) {
            if (u >= 0xD800 && u < 0xE000) continue;
            wchar_t w = (wchar_t)u, o = 0, p = 0;
            LCMapStringEx(L"", LCMAP_UPPERCASE, &w, 1, &o, 1, 0, 0, 0);
            LCMapStringEx(L"", LCMAP_LOWERCASE, &w, 1, &p, 1, 0, 0, 0);
            if ((wchar_t)towupper(w) != o) du++;
            if ((wchar_t)towlower(w) != p) dl++;
        }
        printf("/* towupper/towlower in the C locale differ from LCMapStringEx for %d/%d units */\n", du, dl);
        setlocale(LC_ALL, "de-DE");
        du = dl = 0;
        for (unsigned u = 0; u < 0x10000; u++) {
            if (u >= 0xD800 && u < 0xE000) continue;
            wchar_t w = (wchar_t)u, o = 0, p = 0;
            LCMapStringEx(L"", LCMAP_UPPERCASE, &w, 1, &o, 1, 0, 0, 0);
            LCMapStringEx(L"", LCMAP_LOWERCASE, &w, 1, &p, 1, 0, 0, 0);
            if ((wchar_t)towupper(w) != o) du++;
            if ((wchar_t)towlower(w) != p) dl++;
        }
        printf("/* ... in de-DE for %d/%d units */\n", du, dl);
        setlocale(LC_ALL, "C");
    }

    /* CT_CTYPE1 (GetStringTypeW) as runs {first, last, class} */
    {
        printf("static const uint16_t w32nls_ctype1[][3] = {\n    ");
        int cnt = 0; unsigned rs = 0; WORD rc = 0xFFFF;
        for (unsigned u = 0; u <= 0x10000; u++) {
            WORD c = 0xFFFF;
            if (u < 0x10000) { wchar_t w = (wchar_t)u; c = 0; GetStringTypeW(CT_CTYPE1, &w, 1, &c); }
            if (u == 0 || c != rc) {
                if (u) { printf("{0x%04X,0x%04X,0x%04X},", rs, u - 1, rc); if (++cnt % 5 == 0) printf("\n    "); }
                rs = u; rc = c;
            }
        }
        printf("{0,0,0} };\n");
    }

    /* the CRT's ctype per code page: _pctype, toupper, tolower for 0..255 after
     * setlocale of a locale whose ANSI code page it is */
    {
        const char *cl[] = { "C", "de-DE", "pl-PL", "ru-RU", "tr-TR" };
        const char *cn[] = { "c", "1252", "1250", "1251", "1254" };
        for (int k = 0; k < 5; k++) {
            setlocale(LC_ALL, cl[k]);
            const unsigned short *pt = __pctype_func();
            printf("static const uint16_t w32nls_pctype_%s[256] = {", cn[k]);
            for (int c = 0; c < 256; c++) printf("%s0x%03X", (c & 15) ? "," : (c ? ",\n    " : "\n    "), pt[c]);
            printf(" };\nstatic const uint8_t w32nls_toupper_%s[256] = {", cn[k]);
            for (int c = 0; c < 256; c++) printf("%s0x%02X", (c & 15) ? "," : (c ? ",\n    " : "\n    "), toupper(c) & 0xFF);
            printf(" };\nstatic const uint8_t w32nls_tolower_%s[256] = {", cn[k]);
            for (int c = 0; c < 256; c++) printf("%s0x%02X", (c & 15) ? "," : (c ? ",\n    " : "\n    "), tolower(c) & 0xFF);
            printf(" };\n");
        }
        setlocale(LC_ALL, "C");
    }

    /* named locales: the LCTYPEs below, as UTF-16 */
    static const LCTYPE lt[] = {
        LOCALE_SNAME, LOCALE_SENGLISHLANGUAGENAME, LOCALE_SNATIVELANGUAGENAME, LOCALE_SENGLISHCOUNTRYNAME, LOCALE_SNATIVECOUNTRYNAME,
        LOCALE_SENGLISHDISPLAYNAME, LOCALE_SNATIVEDISPLAYNAME, LOCALE_SISO639LANGNAME, LOCALE_SISO639LANGNAME2, LOCALE_SISO3166CTRYNAME,
        LOCALE_SISO3166CTRYNAME2, LOCALE_SDECIMAL, LOCALE_STHOUSAND, LOCALE_SGROUPING, LOCALE_SLIST, LOCALE_IMEASURE, LOCALE_SNATIVEDIGITS,
        LOCALE_SCURRENCY, LOCALE_SINTLSYMBOL, LOCALE_SMONDECIMALSEP, LOCALE_SMONTHOUSANDSEP, LOCALE_SMONGROUPING, LOCALE_ICURRDIGITS,
        LOCALE_IINTLCURRDIGITS, LOCALE_ICURRENCY, LOCALE_INEGCURR, LOCALE_IDIGITS, LOCALE_ILZERO, LOCALE_INEGNUMBER, LOCALE_SNEGATIVESIGN,
        LOCALE_SPOSITIVESIGN, LOCALE_SSHORTDATE, LOCALE_SLONGDATE, LOCALE_SYEARMONTH, LOCALE_STIMEFORMAT, LOCALE_SSHORTTIME, LOCALE_S1159,
        LOCALE_S2359, LOCALE_IFIRSTDAYOFWEEK, LOCALE_IFIRSTWEEKOFYEAR, LOCALE_IDEFAULTANSICODEPAGE, LOCALE_IDEFAULTCODEPAGE,
        LOCALE_IDEFAULTMACCODEPAGE, LOCALE_ILANGUAGE, LOCALE_ICOUNTRY, LOCALE_SPARENT, LOCALE_SPERCENT, LOCALE_SNAN, LOCALE_SPOSINFINITY,
        LOCALE_SNEGINFINITY, LOCALE_SENGCURRNAME, LOCALE_SNATIVECURRNAME, LOCALE_SDATE, LOCALE_STIME, LOCALE_IDATE, LOCALE_ILDATE,
        LOCALE_ITIME, LOCALE_ITLZERO, LOCALE_ICENTURY, LOCALE_IDAYLZERO, LOCALE_IMONLZERO, LOCALE_SSCRIPTS, LOCALE_SLOCALIZEDDISPLAYNAME,
        LOCALE_SDAYNAME1, LOCALE_SDAYNAME2, LOCALE_SDAYNAME3, LOCALE_SDAYNAME4, LOCALE_SDAYNAME5, LOCALE_SDAYNAME6, LOCALE_SDAYNAME7,
        LOCALE_SABBREVDAYNAME1, LOCALE_SABBREVDAYNAME2, LOCALE_SABBREVDAYNAME3, LOCALE_SABBREVDAYNAME4, LOCALE_SABBREVDAYNAME5,
        LOCALE_SABBREVDAYNAME6, LOCALE_SABBREVDAYNAME7, LOCALE_SSHORTESTDAYNAME1, LOCALE_SSHORTESTDAYNAME2, LOCALE_SSHORTESTDAYNAME3,
        LOCALE_SSHORTESTDAYNAME4, LOCALE_SSHORTESTDAYNAME5, LOCALE_SSHORTESTDAYNAME6, LOCALE_SSHORTESTDAYNAME7,
        LOCALE_SMONTHNAME1, LOCALE_SMONTHNAME2, LOCALE_SMONTHNAME3, LOCALE_SMONTHNAME4, LOCALE_SMONTHNAME5, LOCALE_SMONTHNAME6,
        LOCALE_SMONTHNAME7, LOCALE_SMONTHNAME8, LOCALE_SMONTHNAME9, LOCALE_SMONTHNAME10, LOCALE_SMONTHNAME11, LOCALE_SMONTHNAME12,
        LOCALE_SMONTHNAME13, LOCALE_SABBREVMONTHNAME1, LOCALE_SABBREVMONTHNAME2, LOCALE_SABBREVMONTHNAME3, LOCALE_SABBREVMONTHNAME4,
        LOCALE_SABBREVMONTHNAME5, LOCALE_SABBREVMONTHNAME6, LOCALE_SABBREVMONTHNAME7, LOCALE_SABBREVMONTHNAME8, LOCALE_SABBREVMONTHNAME9,
        LOCALE_SABBREVMONTHNAME10, LOCALE_SABBREVMONTHNAME11, LOCALE_SABBREVMONTHNAME12, LOCALE_SABBREVMONTHNAME13 };
    int nlt = (int)(sizeof lt / sizeof lt[0]);
    printf("#define W32NLS_NLT %d\nstatic const uint32_t w32nls_lctype[W32NLS_NLT] = {", nlt);
    for (int j = 0; j < nlt; j++) printf("%s0x%lX", j ? (j % 8 ? "," : ",\n    ") : "\n    ", (unsigned long)lt[j]);
    printf(" };\n#define W32NLS_NGEN 13\n#define W32NLS_NLOC %d\nstruct w32nls_locale { uint16_t lcid; const uint16_t *s[W32NLS_NLT]; const uint16_t *gen[W32NLS_NGEN]; const uint16_t *gena[W32NLS_NGEN]; };\n", (int)NLOC);
    printf("static const struct w32nls_locale w32nls_locales[W32NLS_NLOC] = {\n");
    for (unsigned i = 0; i < NLOC; i++) {
        printf("  { 0x%04lX, {\n    ", (unsigned long)LocaleNameToLCID(g_locs[i], 0));
        for (int j = 0; j < nlt; j++) {
            wchar_t o[256]; int n = GetLocaleInfoEx(g_locs[i], lt[j], o, 256);
            emit_u16str(o, n > 0 ? n - 1 : 0);
            printf(j % 6 == 5 ? ",\n    " : ", ");
        }
        printf("}, {\n    ");
        for (int j = 0; j < 13; j++) {
            wchar_t o[256]; int n = GetLocaleInfoEx(g_locs[i], (LOCALE_SMONTHNAME1 + j) | LOCALE_RETURN_GENITIVE_NAMES, o, 256);
            if (j == 12) n = GetLocaleInfoEx(g_locs[i], LOCALE_SMONTHNAME13 | LOCALE_RETURN_GENITIVE_NAMES, o, 256);
            emit_u16str(o, n > 0 ? n - 1 : 0);
            printf(j % 6 == 5 ? ",\n    " : ", ");
        }
        printf("}, {\n    ");
        for (int j = 0; j < 13; j++) {
            wchar_t o[256]; int n = GetLocaleInfoEx(g_locs[i], (LOCALE_SABBREVMONTHNAME1 + j) | LOCALE_RETURN_GENITIVE_NAMES, o, 256);
            if (j == 12) n = GetLocaleInfoEx(g_locs[i], LOCALE_SABBREVMONTHNAME13 | LOCALE_RETURN_GENITIVE_NAMES, o, 256);
            emit_u16str(o, n > 0 ? n - 1 : 0);
            printf(j % 6 == 5 ? ",\n    " : ", ");
        }
        printf("} },   /* %s */\n", g_locsa[i][0] ? g_locsa[i] : "invariant");
    }
    printf("};\n");

    /* the symbols' order as CompareStringEx's string sort gives it: each
     * symbol of these ranges with its rank (equal ones one rank) */
    {
        static wchar_t sym[2048]; int ns = 0;
        unsigned rng[][2] = { { 0x20, 0x7F }, { 0xA0, 0xBF }, { 0xD7, 0xD7 }, { 0xF7, 0xF7 }, { 0x2000, 0x206F }, { 0x20A0, 0x20BF } };
        for (unsigned r = 0; r < 6; r++)
            for (unsigned u = rng[r][0]; u <= rng[r][1]; u++) {
                wchar_t w = (wchar_t)u; WORD c = 0; GetStringTypeW(CT_CTYPE1, &w, 1, &c);
                if (c & (C1_ALPHA | C1_DIGIT)) continue;
                sym[ns++] = w;
            }
        for (int i = 1; i < ns; i++) {            /* insertion sort: stable */
            wchar_t k = sym[i]; int j = i - 1;
            while (j >= 0 && CompareStringEx(L"", SORT_STRINGSORT, &sym[j], 1, &k, 1, 0, 0, 0) == CSTR_GREATER_THAN) { sym[j + 1] = sym[j]; j--; }
            sym[j + 1] = k;
        }
        printf("static const uint16_t w32nls_symrank[][2] = {   /* {unit, rank}: the string sort's order of the symbols */\n    ");
        int rank = 1;
        for (int i = 0; i < ns; i++) {
            if (i && CompareStringEx(L"", SORT_STRINGSORT, &sym[i - 1], 1, &sym[i], 1, 0, 0, 0) != CSTR_EQUAL) rank++;
            printf("{0x%04X,%d},", sym[i], rank);
            if ((i + 1) % 8 == 0) printf("\n    ");
        }
        printf("{0,0} };\n#define W32NLS_SYMRANKS %d\n", rank);
    }

    /* setlocale's answers for the forms it takes */
    {
        static const char *forms[] = { "", "de-DE", "German_Germany.1252", "German_Germany", "German", "de", "fr-FR", "ru-RU", "Russian_Russia.1251",
            ".UTF-8", "en-US.UTF-8", "de-DE.UTF-8", ".utf8", ".1251", ".1252", ".437", "English", "en-GB", "sv-SE", "tr-TR", "pl-PL",
            "es-ES", "C", "c", "POSIX", "bogus-XX", "de-DE.1251", "German_Germany.65001", "en", "ja-JP", "zh-CN", "French", "French_France" };
        printf("/* setlocale(LC_ALL, form) -> its answer\n");
        for (unsigned i = 0; i < sizeof forms / sizeof forms[0]; i++) {
            const char *r = setlocale(LC_ALL, forms[i]);
            printf(" *   \"%s\" -> %s\n", forms[i], r ? r : "NULL");
            setlocale(LC_ALL, "C");
        }
        printf(" */\n");
    }
    return 0;
}
