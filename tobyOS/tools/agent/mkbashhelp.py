#!/usr/bin/env python3
"""mkbashhelp.py BUILTINS_C OUT_INC -- tsh's `help` text from GNU bash 5.2.15.

BUILTINS_C is the builtins/builtins.c that bash's mkbuiltins generates (the
WSL build at ~/bash-5.2.15). OUT_INC (src/shell_bashhelp.inc) gets bash's
help table as C data: each topic's name, short doc and long doc, sorted as
bash sorts its table (strcmp order). The text is bash's own, carried verbatim
by the user's decision (Oils 0644, 2026-10-13): GPLv3+, Copyright (C)
1987-2022 Free Software Foundation, Inc. This script is tsh's.

The table is the one a default Linux build has: every #if below resolves as
config.h has it there (logs/b27 checks the result against the guest's bash).
"""
import re
import sys

DEFINED = {"ALIAS", "READLINE", "DEBUGGER", "V9_ECHO", "HISTORY", "JOB_CONTROL",
           "HELP_BUILTIN", "PROGRAMMABLE_COMPLETION", "PUSHD_AND_POPD"}

def active_lines(text):
    """The lines of TEXT that the preprocessor keeps, by DEFINED."""
    out, stack = [], []
    for line in text.split("\n"):
        m = re.match(r"#if\s+(!?)defined\s*\((\w+)\)\s*$", line)
        if m:
            on = (m.group(2) in DEFINED) != (m.group(1) == "!")
            stack.append(on)
            continue
        if re.match(r"#else\b", line):
            stack[-1] = not stack[-1]
            continue
        if re.match(r"#endif\b", line):
            stack.pop()
            continue
        if line.startswith("#"):
            if all(stack):
                out.append(line)
            continue
        if all(stack):
            out.append(line)
    if stack:
        sys.exit("unbalanced #if")
    return "\n".join(out)

ESC = {"n": "\n", "t": "\t", '"': '"', "\\": "\\", "'": "'", "a": "\a"}

def c_string(body):
    """A C string literal's value: BODY is the text between the quotes."""
    body = body.replace("\\\n", "")            # line splices
    out, i = [], 0
    while i < len(body):
        c = body[i]
        if c != "\\":
            out.append(c)
            i += 1
            continue
        n = body[i + 1]
        if n in ESC:
            out.append(ESC[n])
            i += 2
        elif n in "01234567":
            j = i + 1
            while j < len(body) and j < i + 4 and body[j] in "01234567":
                j += 1
            out.append(chr(int(body[i + 1:j], 8)))
            i = j
        else:
            sys.exit("unknown escape \\%s" % n)
    return "".join(out)

LIT = r'N_\("((?:[^"\\]|\\.|\\\n)*)"\)'

def c_quote(s):
    """S as a C string literal, split at its newlines for reading."""
    parts = []
    for piece in re.split(r"(?<=\n)", s):
        if not piece:
            continue
        q = (piece.replace("\\", "\\\\").replace('"', '\\"')
             .replace("\n", "\\n").replace("\t", "\\t"))
        parts.append('"%s"' % q)
    return "\n        ".join(parts) if parts else '""'

def main():
    src, dst = sys.argv[1], sys.argv[2]
    text = active_lines(open(src, encoding="latin-1").read().replace("\r\n", "\n"))
    table = re.search(r"struct builtin static_shell_builtins\[\] = \{(.*?)\n  \{ \(char \*\)0x0", text, re.S)
    if not table:
        sys.exit("no builtin table")
    # the short doc is N_("...") or, for : true false, a bare "..."
    entries = re.findall(r'\{ "((?:[^"\\]|\\.)*)", ([^,]*), ([^,]*), (\w+),\s*'
                         r'(?:N_\()?"((?:[^"\\]|\\.)*)"\)?, \(char \*\)NULL \}', table.group(1))
    if len(entries) != table.group(1).count("\n  { "):
        sys.exit("parsed %d of %d entries" % (len(entries), table.group(1).count("\n  { ")))
    topics = []
    for name, func, flags, docsym, short in entries:
        m = re.search(r"char \* const %s\[\] = \{\n(.*?)\n  \(char \*\)NULL\n\};" % re.escape(docsym), text, re.S)
        if not m:
            sys.exit("no doc for %s" % docsym)
        lits = re.findall(LIT, m.group(1))
        if len(lits) != 1:
            sys.exit("%s: %d strings" % (docsym, len(lits)))
        # a reserved word's topic has no function: not a builtin
        topics.append((c_string(name), c_string(short), c_string(lits[0]),
                       "0x0" not in func))
    topics.sort(key=lambda t: t[0].encode())
    with open(dst, "w", newline="\n") as f:
        f.write("/* GENERATED by tools/agent/mkbashhelp.py from GNU bash 5.2.15's\n"
                " * builtins/builtins.c -- do not edit; rerun the script.\n"
                " *\n"
                " * The text below is bash's own: Copyright (C) 1987-2022 Free\n"
                " * Software Foundation, Inc., GNU GPL version 3 or later. tsh carries\n"
                " * it verbatim by the user's decision (Oils 0644, 2026-10-13) so that\n"
                " * `help` says what bash says. Sorted as bash sorts its table.\n"
                " *\n"
                " * Each topic: its name, its synopsis (the short doc -- also the\n"
                " * usage line a builtin prints on a bad option), whether it is a\n"
                " * builtin rather than a reserved word's topic, and its long doc,\n"
                " * which `help` prints after four spaces. */\n")
        f.write("struct sh_bash_topic { const char *name; const char *syn; bool bi; const char *doc; };\n")
        f.write("static const struct sh_bash_topic g_bash_topics[] = {\n")
        for name, short, long_, bi in topics:
            f.write("    { %s, %s, %s,\n        %s },\n" % (c_quote(name), c_quote(short),
                                                        "true" if bi else "false", c_quote(long_)))
        f.write("    { 0, 0, false, 0 },\n};\n")
        f.write("#define SH_BASH_TOPICS %d\n" % len(topics))
    print("%d topics -> %s" % (len(topics), dst))

if __name__ == "__main__":
    main()
