#!/usr/bin/env python3
"""wctab_gen.py DUMP... -- build include/tobyos/wctab.h from dumps of musl's
wide-character functions taken on the guest (tools/agent/wcdump.py, run by
the guest's musl CPython: one file per code-point range, each ending with an
END line). Every lookup the header makes is replayed here against the dumps
for every code point before the header is written.

The header holds, for every code point from 0x80 on, musl's answer to the
twelve isw* class functions (as sorted, disjoint ranges) and to towupper and
towlower (as runs lo..hi, step 1 or 2, mapping c to c + delta), and the
static functions that read them. tsh (both builds) and libtoby's regex
include it, so all three agree with the bash they are measured against."""
import sys

CLASSES = ['alpha', 'digit', 'alnum', 'upper', 'lower', 'space', 'blank',
           'print', 'graph', 'cntrl', 'punct', 'xdigit']

WIDTHS = ['wcw0', 'wcw2', 'wcwn']
ranges = {c: [] for c in CLASSES + WIDTHS}
maps = {'U': {}, 'L': {}}
covered = []
for path in sys.argv[1:]:
    for line in open(path):
        f = line.split()
        if not f:
            continue
        if f[0] == 'C':
            ranges[f[1][3:]].append((int(f[2], 16), int(f[3], 16)))
        elif f[0] in ('U', 'L'):
            maps[f[0]][int(f[1], 16)] = int(f[2], 16)
        elif f[0] == 'END':
            covered.append((int(f[1], 16), int(f[2], 16)))

covered.sort()
pos = 0x80
for lo, hi in covered:
    if lo != pos:
        sys.exit('dumps do not cover %x..%x' % (pos, lo))
    pos = hi
if pos != 0x110000:
    sys.exit('dumps stop at %x' % pos)

def merge(rs):
    rs.sort()
    out = []
    for lo, hi in rs:
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], hi))
        else:
            out.append((lo, hi))
    return out

def runs(m):
    """(lo, hi, delta, step) runs covering every mapped code point exactly."""
    keys = sorted(m)
    out = []
    i = 0
    while i < len(keys):
        c = keys[i]
        d = m[c] - c
        best = (c, c, d, 1)
        for step in (1, 2):
            j = i
            last = c
            while j + 1 < len(keys) and keys[j + 1] == last + step and \
                    m[keys[j + 1]] - keys[j + 1] == d:
                j += 1
                last = keys[j]
            if last > best[1]:
                best = (c, last, d, step)
                nxt = j
        if best[1] == c:
            nxt = i
        out.append(best)
        i = nxt + 1
    # the runs must reproduce the map exactly, and touch nothing else
    check = {}
    for lo, hi, d, st in out:
        for x in range(lo, hi + 1, st):
            check[x] = x + d
    if check != m:
        sys.exit('run compression lost information')
    return out

# REPLAY every lookup the header will make, for every code point, against
# the dumps: the class and width ranges as merged, and the case maps through
# the same binary search over runs that wc_toupper/wc_tolower do.
def bits(rs):
    b = bytearray(0x110000)
    for lo, hi in rs:
        b[lo:hi + 1] = b'\x01' * (hi - lo + 1)
    return b

for c in CLASSES + WIDTHS:
    if bits(merge(list(ranges[c]))) != bits(ranges[c]):
        sys.exit('merging changed class %s' % c)
for tag in ('U', 'L'):
    rs = runs(maps[tag])
    for a, b in zip(rs, rs[1:]):
        if a[1] >= b[0]:
            sys.exit('%s runs overlap at %x' % (tag, b[0]))
    los = [r[0] for r in rs]
    import bisect
    for c in range(0x80, 0x110000):
        k = bisect.bisect_right(los, c) - 1
        got = c
        if k >= 0 and c <= rs[k][1] and (c - rs[k][0]) % rs[k][3] == 0:
            got = c + rs[k][2]
        if got != maps[tag].get(c, c):
            sys.exit('%s lookup wrong at %x: %x, want %x' % (tag, c, got, maps[tag].get(c, c)))

o = []
o.append('/* wctab.h -- musl\'s wide-character classes and case maps, for code')
o.append(' * points from 0x80 on. GENERATED by tools/agent/wctab_gen.py from dumps')
o.append(' * of the guest\'s musl (tools/agent/wcdump.py) -- do not edit. musl is MIT')
o.append(' * licensed; these are its answers, tabulated.')
o.append(' *')
o.append(' * The bash tsh is measured against runs on musl, so its classes and case')
o.append(' * maps ARE these: [[:alpha:]], ${s^^}, nocasematch, =~ (logs/b13 q2).')
o.append(' * Included by src/shell.c and libtoby/src/regex.c. */')
o.append('#ifndef TOBYOS_WCTAB_H')
o.append('#define TOBYOS_WCTAB_H')
o.append('')
o.append('#include <stdint.h>')
o.append('')
o.append('enum {')
for i, c in enumerate(CLASSES):
    o.append('    WC_%s = %d,' % (c.upper(), i))
o.append('    WC_NCLASS = %d' % len(CLASSES))
o.append('};')
o.append('')
for c in CLASSES:
    rs = merge(ranges[c])
    o.append('static const uint32_t wc_r_%s[][2] = {' % c)
    if not rs:
        o.append('    { 1, 0 },')
    for lo, hi in rs:
        o.append('    { 0x%x, 0x%x },' % (lo, hi))
    o.append('};')
o.append('')
for c in WIDTHS:
    rs = merge(ranges[c])
    o.append('static const uint32_t wc_r_%s[][2] = {' % c)
    if not rs:
        o.append('    { 1, 0 },')
    for lo, hi in rs:
        o.append('    { 0x%x, 0x%x },' % (lo, hi))
    o.append('};')
o.append('')
o.append('__attribute__((unused))')
o.append('static int wc_in(const uint32_t (*r)[2], unsigned n, uint32_t c) {')
o.append('    unsigned lo = 0, hi = n;')
o.append('    while (lo < hi) {')
o.append('        unsigned mid = (lo + hi) / 2;')
o.append('        if (c < r[mid][0]) hi = mid;')
o.append('        else if (c > r[mid][1]) lo = mid + 1;')
o.append('        else return 1;')
o.append('    }')
o.append('    return 0;')
o.append('}')
o.append('')
o.append("/* musl's wcwidth for C >= 0x80: 0, 2, -1 (not printable), else 1. */")
o.append('__attribute__((unused))')
o.append('static int wc_width(uint32_t c) {')
o.append('    if (wc_in(wc_r_wcw0, sizeof wc_r_wcw0 / sizeof wc_r_wcw0[0], c)) return 0;')
o.append('    if (wc_in(wc_r_wcw2, sizeof wc_r_wcw2 / sizeof wc_r_wcw2[0], c)) return 2;')
o.append('    if (wc_in(wc_r_wcwn, sizeof wc_r_wcwn / sizeof wc_r_wcwn[0], c)) return -1;')
o.append('    return 1;')
o.append('}')
o.append('')
o.append('static const struct { const uint32_t (*r)[2]; unsigned n; } wc_class_tab[] = {')
for c in CLASSES:
    o.append('    { wc_r_%s, sizeof wc_r_%s / sizeof wc_r_%s[0] },' % (c, c, c))
o.append('};')
o.append('')
for tag, nm in (('U', 'upper'), ('L', 'lower')):
    rs = runs(maps[tag])
    o.append('static const struct { uint32_t lo, hi; int32_t d; uint32_t st; } wc_m_%s[] = {' % nm)
    for lo, hi, d, st in rs:
        o.append('    { 0x%x, 0x%x, %d, %d },' % (lo, hi, d, st))
    o.append('};')
o.append('')
o.append('/* Is C (>= 0x80) in class K? */')
o.append('__attribute__((unused))')
o.append('static int wc_class(int k, uint32_t c) {')
o.append('    if (k < 0 || k >= WC_NCLASS) return 0;')
o.append('    const uint32_t (*r)[2] = wc_class_tab[k].r;')
o.append('    unsigned lo = 0, hi = wc_class_tab[k].n;')
o.append('    while (lo < hi) {')
o.append('        unsigned mid = (lo + hi) / 2;')
o.append('        if (c < r[mid][0]) hi = mid;')
o.append('        else if (c > r[mid][1]) lo = mid + 1;')
o.append('        else return 1;')
o.append('    }')
o.append('    return 0;')
o.append('}')
o.append('')
for nm in ('upper', 'lower'):
    o.append('__attribute__((unused))')
    o.append('static uint32_t wc_to%s(uint32_t c) {' % nm)
    o.append('    unsigned lo = 0, hi = sizeof wc_m_%s / sizeof wc_m_%s[0];' % (nm, nm))
    o.append('    while (lo < hi) {')
    o.append('        unsigned mid = (lo + hi) / 2;')
    o.append('        if (c < wc_m_%s[mid].lo) hi = mid;' % nm)
    o.append('        else if (c > wc_m_%s[mid].hi) lo = mid + 1;' % nm)
    o.append('        else return (c - wc_m_%s[mid].lo) %% wc_m_%s[mid].st == 0' % (nm, nm))
    o.append('                    ? (uint32_t)((int32_t)c + wc_m_%s[mid].d) : c;' % nm)
    o.append('    }')
    o.append('    return c;')
    o.append('}')
    o.append('')
o.append('/* The class named NAME (N bytes) -- "alpha" and the rest -- or -1. */')
o.append('__attribute__((unused))')
o.append('static int wc_class_id(const char *name, unsigned long n) {')
o.append('    static const char *const nm[] = {')
o.append('        ' + ', '.join('"%s"' % c for c in CLASSES) + ', 0 };')
o.append('    for (int k = 0; nm[k]; k++) {')
o.append('        unsigned long l = 0;')
o.append('        while (nm[k][l]) l++;')
o.append('        if (l != n) continue;')
o.append('        unsigned long i = 0;')
o.append('        while (i < n && nm[k][i] == name[i]) i++;')
o.append('        if (i == n) return k;')
o.append('    }')
o.append('    return -1;')
o.append('}')
o.append('')
o.append('#endif')
open('include/tobyos/wctab.h', 'w', newline='\n').write('\n'.join(o) + '\n')
print('ok', {c: len(merge(ranges[c])) for c in CLASSES},
      'upper', len(runs(maps['U'])), 'lower', len(runs(maps['L'])))
