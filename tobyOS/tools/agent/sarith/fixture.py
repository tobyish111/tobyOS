"""The arithmetic cases as ONE shparity fixture.

    fixture.py CASES OUT.sh

Each case of CASES ("SETUP<TAB>EXPR", see harness.c) becomes a subshell
that sets the variables up, prints `$(( EXPR ))` and then the variables,
so an error that discards the line or ends the shell (set -u) ends only
that case; the subshell's status follows. bash and /bin/tsh run the same
file on the guest (logs/shparity.sh) -- the host comparison, harness.c
against bash 5.2 in WSL, is tools/agent/sarith/run-bash.sh.
"""
import sys

NAMES = "a b c i j k m n x y z s t u v w".split()
HEAD = """# BASH'S ARITHMETIC EVALUATOR (expr.c), case by case: every base and
# constant form, every operator and its precedence, assignment operators,
# ++/--, the short-circuit of && || ?: (no side effects, no errors in the
# arm not taken), recursive evaluation of variables holding expressions,
# array elements, and the errors in bash's words -- "EXPR: MSG (error
# token is "T")". Generated by tools/agent/sarith/fixture.py from the
# cases the host harness compares with bash (tools/agent/sarith).
exec 2>&1
"""


def main():
    cases, out = sys.argv[1], sys.argv[2]
    lines = [HEAD]
    n = 0
    for line in open(cases, encoding='utf-8'):
        line = line.rstrip('\n').rstrip('\r')
        if not line or line.startswith('#') or '\t' not in line:
            continue
        setup, expr = line.split('\t', 1)
        n += 1
        body = []
        assoc = set()
        for t in setup.split():
            if t == '-u':
                body.append('set -u')
                continue
            name, val = t.split('=', 1)
            val = val.replace('\\s', ' ')
            if '[' in name:
                body.append(f"{name}='{val}'")
            elif '{' in name:
                nm, key = name.split('{', 1)
                key = key.rstrip('}')
                if nm not in assoc:
                    body.append(f'declare -A {nm}')
                    assoc.add(nm)
                body.append(f"{nm}[{key}]='{val}'")
            else:
                body.append(f"{name}='{val}'")
        body.append(f'echo "c{n} [$(( {expr} ))]"')
        body.append('for __n in ' + ' '.join(NAMES) +
                    '; do declare -p $__n 2>/dev/null; done')
        lines.append('( ' + '; '.join(body) + ' )')
        lines.append(f'echo "c{n} status=$?"')
    with open(out, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(n, 'cases')


if __name__ == '__main__':
    main()
