(exit 10) & sleep 0.2; (exit 11) & sleep 0.2; wait; wait -n; echo "two plain-waited, wait -n: $?"; wait -n; echo "then: $?"; wait -n; echo "then: $?"
(exit 12) & sleep 0.2; wait -n -p v; echo "finished first, -p: $? [$([ -n "$v" ] && echo set)]"
