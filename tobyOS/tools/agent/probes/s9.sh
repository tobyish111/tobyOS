# S9 + S14: wait -n / -p / -f and kill -n, against the guest's bash.
echo x & wait -n $! bad; echo "n with bad id: $?"
wait -n bad; echo "n only bad: $?"
wait -n; echo "n nothing: $?"
wait -n 99999; echo "n unknown pid: $?"
wait -p; echo "p no name: $?"
wait -p 1bad; echo "p invalid name: $?"
(exit 3) & p=$!; wait -p v $p; echo "p one: $? [$([ "$v" = "$p" ] && echo pid)]"
(exit 4) & p=$!; wait -n -p w; echo "n p: $? [$([ "$w" = "$p" ] && echo pid)]"
v=keep; wait -p v; echo "p no jobs: $? [${v-unset}]"
wait -x; echo "bad option: $?"
(exit 5) & wait -f $!; echo "f: $?"
{ sleep 0.2; exit 9; } & { sleep 0.05; exit 3; } & wait -n; echo "first: $?"; wait -n; echo "second: $?"
sleep 5 & k=$!; kill -n 9 $k; echo "kill -n: $?"; wait $k; echo "killed: $?"
sleep 5 & k=$!; kill -s 15 $k; echo "kill -s num: $?"; wait $k; echo "termed: $?"
sleep 5 & k=$!; kill -n TERM $k; echo "kill -n name: $?"; wait $k; echo "termed: $?"
kill -n 99 $$; echo "kill -n 99: $?"
kill -n; echo "kill -n alone: $?"
echo done
