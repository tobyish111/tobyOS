#!/bin/bash
# hwgate.sh -- run distro-gate sections ON THE REAL ELITEDESK and grade them
# with the very same checks logs/distrotail.sh applies to a QEMU boot.
#
#   bash logs/hwgate.sh                      # the default set (below)
#   bash logs/hwgate.sh clock ps_ sh_        # section-name prefixes
#   bash logs/hwgate.sh --list               # what the fixture offers
#
# Why this exists: five of the six bugs found in the first week of real-
# hardware work were invisible in QEMU, and the loop for finding them was
# "boot the box, read serial, paste a log". This is one command that returns
# a hardware verdict, per section, with no serial cable.
#
# How: the selected sections are cut out of etc/distro_test.sh by their
# `echo @@name` markers, prefixed with a stamp to /data/hwgate.txt (the USB
# stick survives a wedge and a reboot, so the last stamp names the section
# that killed the box), uploaded over tobyOS's own SSH through
# logs/edremote.sh, and the transcript is handed to logs/distrochecks.sh --
# the check block distrotail.sh sources -- with SELECT set so only the
# chosen sections are graded.
#
# Exit: 0 all selected checks passed; 1 a check failed; 90-92 the box was
# not reachable (edremote's codes: off, port shut, WEDGED).
set -u
cd "$(dirname "$0")/.." || exit 1
FIX=etc/distro_test.sh
OUTF=logs/hwgate.out
REMOTE=logs/hwgate.remote.sh

if [ "${1:-}" = "--list" ]; then
    grep -o '^echo @@[a-z_0-9]*' "$FIX" | sed 's/^echo @@/  /'
    exit 0
fi

PREFIXES=("$@")
# pstat_ is in the default set because the clock checks read btime from it.
[ ${#PREFIXES[@]} -gt 0 ] || PREFIXES=(pstat_ clock_ ps_ sh_ strace_native)

# ---- cut the sections out of the fixture -----------------------------------
python - "$FIX" "$REMOTE" "${PREFIXES[@]}" <<'PY'
import re, sys
fix, out = sys.argv[1], sys.argv[2]
prefixes = sys.argv[3:]
lines = open(fix, encoding="utf-8", errors="replace").read().replace("\r\n", "\n").split("\n")
sections = []          # (name, [lines])
cur = None
for ln in lines:
    m = re.match(r"^echo @@([a-z_0-9]+)\s*$", ln)
    if m:
        cur = (m.group(1), [ln])
        sections.append(cur)
    elif cur is not None:
        cur[1].append(ln)
chosen = [s for s in sections if any(s[0].startswith(p) for p in prefixes)
          and s[0] not in ("dt_BEGIN", "dt_END")]
if not chosen:
    sys.stderr.write("hwgate: no section matches %r\n" % (prefixes,))
    sys.exit(2)
w = open(out, "w", newline="\n")
w.write("# generated by logs/hwgate.sh -- do not edit\n")
w.write("cd /tmp\n: > /data/hwgate.txt\necho @@dt_BEGIN\n")
for name, body in chosen:
    w.write('echo "%s" >> /data/hwgate.txt\n' % name)
    w.write("\n".join(body).rstrip("\n") + "\n")
w.write('echo "done" >> /data/hwgate.txt\necho @@dt_END\n')
w.close()
sys.stderr.write("hwgate: %d section(s): %s\n" % (len(chosen), " ".join(n for n, _ in chosen)))
PY
rc=$?; [ $rc -eq 0 ] || exit $rc

# ---- run it on the box -----------------------------------------------------
# The fixture's longest section is the strace loop (ten traces, each bounded
# at 40 s); 900 s bounds the whole script without ever killing the client
# mid-session, which edremote's notes forbid.
: > "$OUTF"
ED_TIMEOUT="${ED_TIMEOUT:-900}" bash logs/edremote.sh -f "$REMOTE" > "$OUTF" 2>logs/hwgate.err
rc=$?
if [ $rc -ge 90 ] && [ $rc -le 93 ]; then
    cat logs/hwgate.err >&2
    echo "hwgate: the box did not run the script (edremote exit $rc)"
    exit $rc
fi
OUT=$(tr -d '\r' < "$OUTF")
if ! echo "$OUT" | grep -q "@@dt_END"; then
    echo "hwgate: the transcript is INCOMPLETE -- the box stopped answering."
    echo "        The last stamp in /data/hwgate.txt on the box names the section."
    echo "$OUT" | tail -5
    bash logs/edremote.sh --check
    exit 1
fi

# ---- grade it with the QEMU gate's own checks --------------------------------
LOG="$OUTF"
SELECT="${PREFIXES[*]}"
echo "=== hardware verdict: $(bash logs/edremote.sh 'uname -a' 2>/dev/null | tr -d '\r') ==="
. logs/distrochecks.sh
